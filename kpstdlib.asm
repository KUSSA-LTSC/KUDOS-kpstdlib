; string

global  kp_strlen
global  kp_strchr


%include 'kp_string.asm'

section kpifuncs code

; strlen
kp_strlen:
    jmp qword [kpic_string.strlen]

; strchr
kp_strchr:
    jmp qword [kpic_string.strchr]










section .data

kpic_string:
    .strlen dq k1_strlen_2610
    .strchr dq k1_strchr_2610

kpic_string_end:

section .text

kpicinit:

    push rbx

    mov eax, 1
    cpuid
    bt  ecx, 28
    jnc .exit
    bt  ecx, 27
    jnc .exit

    mov eax, 7
    xor ecx, ecx
    cpuid
    bt  ebx, 5
    jnc .exit
    
    xor ecx, ecx
    xgetbv
    and eax, 6
    cmp eax, 6
    jne .exit

    lea rdx,   [kpic_string.strlen]
    lea rax,   [k7_strlen_2610]
    mov [rdx], rax

    lea rdx,   [kpic_string.strchr]
    lea rax,   [k5_strchr_2610]
    mov [rdx], rax

    mov eax, 1
    pop rbx
    ret

.exit:

    pop rbx
    xor eax, eax
    ret











